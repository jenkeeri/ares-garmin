#!/usr/bin/env bash
# Build the Ares watch projects.
#   scripts/build.sh [datafield|app|all] [device]          (default: all fenix847mm)
# Config (env or .env in repo root):
#   RELAY_URL     https URL of the relay compiled in as default (sideloaded apps can't be
#                 configured from Garmin Connect; app settings only override when non-empty)
#   RELAY_KEY     relay access key
#   TRANSPORT     0 = relay (default), 1 = Ares Bridge iPhone app
#   POLL_SECONDS  default 5
#   CIQ_SDK       SDK dir (default: from SDK Manager current-sdk.cfg)
#   DEV_KEY       developer key .der (default: ~/ciq/keys/developer_key.der)
#   RELEASE=1     build .iq store package instead of a device .prg
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
[ -f "$ROOT/.env" ] && set -a && . "$ROOT/.env" && set +a

WHAT="${1:-all}"
DEVICE="${2:-fenix847mm}"
CIQ_HOME="$HOME/Library/Application Support/Garmin/ConnectIQ"
CIQ_SDK="${CIQ_SDK:-$(cat "$CIQ_HOME/current-sdk.cfg" 2>/dev/null || true)}"
CIQ_SDK="${CIQ_SDK%/}"
DEV_KEY="${DEV_KEY:-$HOME/ciq/keys/developer_key.der}"
[ -x "$CIQ_SDK/bin/monkeyc" ] || { echo "Connect IQ SDK not found (set CIQ_SDK)"; exit 1; }
[ -f "$DEV_KEY" ] || { echo "Developer key missing: $DEV_KEY (see docs/WATCH_SETUP.md)"; exit 1; }

# Defaults are compiled into code (AresBuild) rather than property defaults: the watch keeps
# stored property values across sideloads, so a changed RELAY_URL would otherwise be ignored.
mcstr() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
mkdir -p "$ROOT/watch/build-config"
cat > "$ROOT/watch/build-config/AresBuild.mc" <<MC
// Generated by scripts/build.sh. Do not edit.
module AresBuild {
    const RELAY_URL = "$(mcstr "${RELAY_URL:-}")";
    const RELAY_KEY = "$(mcstr "${RELAY_KEY:-}")";
    const TRANSPORT = ${TRANSPORT:-0};
    const POLL_SECONDS = ${POLL_SECONDS:-5};
}
MC

mkdir -p "$ROOT/build"
build() {
  local proj="$1" name="$2"
  if [ "${RELEASE:-0}" = "1" ]; then
    "$CIQ_SDK/bin/monkeyc" -f "$ROOT/watch/$proj/monkey.jungle" -o "$ROOT/build/$name.iq" -y "$DEV_KEY" -e -r -w
  else
    "$CIQ_SDK/bin/monkeyc" -f "$ROOT/watch/$proj/monkey.jungle" -d "$DEVICE" -o "$ROOT/build/$name.prg" -y "$DEV_KEY" -l 2 -w ${DEBUG:+-g}
  fi
  echo "built build/$name.$([ "${RELEASE:-0}" = 1 ] && echo iq || echo prg)"
}
case "$WHAT" in
  datafield) build datafield AresRadar ;;
  app) build app AresMap ;;
  all) build datafield AresRadar; build app AresMap ;;
  *) echo "unknown target $WHAT"; exit 1 ;;
esac
